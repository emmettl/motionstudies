import { expect, test, type Page } from '@playwright/test'

async function seek(page: Page, label: string, value: string) {
  const slider = page.getByRole('slider', { name: label, exact: true })
  await slider.fill(String(Number(value)))
}

test.beforeEach(async ({ page }) => { await page.goto('/') })

test('terrain swaps a live GPU texture, adapts rows and preserves the masked path on remount', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.getByRole('button', { name: /Terrain$/ }).click()
  const canvas = page.locator('.scene-preview canvas')
  const audit = async () => JSON.parse(await canvas.getAttribute('data-terrain-audit') ?? '{}')
  await expect.poll(async () => (await audit()).phase).toBe(0)
  const first = await audit()
  await expect(canvas).toHaveScreenshot('terrain-initial.png', { maxDiffPixelRatio: .02 })
  await page.getByRole('button', { name: 'Swap height texture' }).click()
  await expect.poll(async () => (await audit()).phase).toBe(1)
  expect((await audit()).geometry).toBe(first.geometry)
  expect((await audit()).texture).not.toBe(first.texture)
  await page.getByLabel('South-first texture adapter').check()
  await expect.poll(async () => (await audit()).southFirst).toBe(true)
  await expect(canvas).toHaveScreenshot('terrain-swapped.png', { maxDiffPixelRatio: .02 })
  const adapted = await canvas.screenshot()
  await page.getByLabel('South-first texture adapter').uncheck()
  // A change of texture storage order with its matching adapter must preserve the rendered landscape.
  await expect(canvas).toHaveScreenshot('terrain-swapped.png', { maxDiffPixelRatio: .02 })
  await testInfo.attach('south-first-adapted', { body: adapted, contentType: 'image/png' })
  await seek(page, 'Terrain path progress', '.5')
  await expect(page.getByTestId('terrain-mask')).toContainText('Hidden')
  await expect.poll(async () => (await audit()).hidden).toBe(true)
  await page.getByLabel('Visibility mask', { exact: true }).uncheck()
  await expect.poll(async () => (await audit()).hidden).toBe(false)
  await seek(page, 'Terrain exaggeration', '3')
  await page.getByLabel('Wireframe', { exact: true }).check()
  await page.getByRole('button', { name: 'Unmount terrain' }).click()
  await expect(canvas).toHaveCount(0)
  await page.getByRole('button', { name: 'Mount terrain' }).click()
  await expect.poll(async () => (await audit()).phase).toBe(1)
  expect((await audit()).geometry).not.toBe(first.geometry)
  expect(errors).toEqual([])
})

test('network policies update a paused scene through density, portrait framing and branching morphs', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.getByRole('button', { name: /Network policies$/ }).click()
  const canvas = page.locator('.policy-scene canvas')
  const audit = async () => JSON.parse(await canvas.getAttribute('data-style-audit') ?? '{}')
  await expect.poll(async () => (await audit()).trains?.length ?? 0).toBeGreaterThan(0)
  await expect(canvas).toHaveScreenshot('network-branching.png', { maxDiffPixelRatio: .02 })
  await page.getByLabel('Dense traffic').check()
  await expect.poll(async () => new Set((await audit()).trains).size).toBeGreaterThan(3)
  await seek(page, 'Label budget', '0')
  await expect.poll(async () => (await audit()).labels?.length).toBe(0)
  await seek(page, 'Label budget', '48')
  await expect.poll(async () => (await audit()).labels?.length).toBeGreaterThan(0)
  for (const selection of ['station', 'service', 'route', 'comparison', 'none']) await page.getByLabel('Policy selection').selectOption(selection)
  await seek(page, 'Label height', '24')
  await seek(page, 'Label offset', '-20')
  await seek(page, 'Viewport padding', '30')
  await page.getByLabel('Coplanar surfaces').check()
  await expect.poll(async () => (await audit()).heights?.every((h: number) => h === 0)).toBe(true)
  await seek(page, 'Material opacity', '0')
  await expect.poll(async () => (await audit()).gridOpacity).toBe(0)
  await seek(page, 'Material opacity', '1')
  await expect.poll(async () => (await audit()).gridOpacity).toBeCloseTo(.1)
  await page.getByLabel('Portrait canvas').check()
  await page.getByLabel('Authored viewport').check()
  await seek(page, 'Policy layout mix', '.5')
  await expect.poll(async () => (await audit()).cameraZoom).toBeCloseTo(1.15)
  await expect(canvas).toHaveScreenshot('network-dense-portrait.png', { maxDiffPixelRatio: .02 })
  await page.getByLabel('Authored viewport').uncheck()
  await expect.poll(async () => (await audit()).cameraZoom).toBe(1)
  await seek(page, 'Local detail scale', '.4')
  await page.getByRole('button', { name: 'focus-location', exact: true }).click()
  await page.getByLabel('Topology-preserving morph').check()
  for (const mix of ['0', '.25', '.5', '.75', '1']) {
    await seek(page, 'Policy layout mix', mix)
    await seek(page, 'Policy time', '120')
    await expect(page.getByTestId('policy-time')).toHaveText('120 s')
    await expect.poll(async () => {
      const state = await audit()
      const train = state.trainPositions?.find((p: { id: string }) => p.id === 'dense-0')
      const stop = state.projectedStops?.[1]
      return train && stop ? Math.hypot(train.x - stop[0], train.z - stop[2]) : Infinity
    }).toBeLessThan(.001)
  }
  await page.getByRole('button', { name: 'reset', exact: true }).click()
  await page.getByRole('button', { name: 'Unmount policies' }).click()
  await expect(canvas).toHaveCount(0)
  await page.getByRole('button', { name: 'Mount policies' }).click()
  await expect(canvas).toHaveCount(1)
  await expect(page.getByTestId('policy-time')).toHaveText('120 s')
  expect(errors).toEqual([])
})

test('power days distinguish signed energy, zero, missing evidence and civil-time repeats', async ({ page }) => {
  await page.getByRole('button', { name: /Power days$/ }).click()
  const table = page.getByTestId('power-readout')
  await expect(table).toContainText('-2 MWh')
  await expect(table).toContainText('-4 MW')
  await expect(page.getByTestId('power-total')).toContainText('4 MW · 2 available · 0 missing')
  await page.getByLabel('Include storage in aggregate').uncheck()
  await expect(page.getByTestId('power-total')).toContainText('8 MW · 1 available')
  await page.getByRole('button', { name: '300 s', exact: true }).click()
  await expect(page.getByTestId('power-fuel')).toContainText('expired')
  await page.getByRole('button', { name: '600 s', exact: true }).click()
  await expect(page.getByTestId('power-fuel')).toContainText('WIND: 20 MW')
  await page.getByRole('button', { name: '1800 s', exact: true }).click()
  await expect(table).toContainText('0 MWh')
  await page.getByRole('button', { name: '3600 s', exact: true }).click()
  await expect(page.getByTestId('power-total')).toContainText('Missing · 0 available · 1 missing')
  await page.getByRole('button', { name: 'Day end', exact: true }).click()
  await expect(table).not.toContainText(' MW')
  await page.getByLabel('Power civil day').selectOption('short')
  await expect(page.getByTestId('power-day-length')).toContainText('46 half-hour periods')
  await page.getByRole('button', { name: '3600 s', exact: true }).click()
  await expect(page.getByTestId('power-clock')).toContainText('02:00 BST')
  await page.getByLabel('Power civil day').selectOption('long')
  await expect(page.getByTestId('power-day-length')).toContainText('50 half-hour periods')
  await page.getByRole('button', { name: '3600 s', exact: true }).click()
  await expect(page.getByTestId('power-clock')).toContainText('01:00 BST')
  await page.getByRole('button', { name: '7200 s', exact: true }).click()
  await expect(page.getByTestId('power-clock')).toContainText('01:00 GMT')
})
