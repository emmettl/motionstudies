import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Airports', exact: false }).click()
})

test('airport boards switch direction, select flights and update values', async ({ page }) => {
  const hero = page.getByRole('region', { name: 'Northfield International', exact: true })
  const departures = hero.getByRole('table', { name: 'NFL Departures' })
  await expect(departures.getByRole('row')).toHaveCount(5)
  const flight = departures.getByRole('button', { name: 'NF 204' })
  await flight.focus()
  await page.keyboard.press('Enter')
  await expect(flight).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('selected-flight')).toHaveText('Selected flight: nf204')
  await page.getByRole('button', { name: 'Update flight' }).click()
  await expect(departures.getByRole('row').filter({ has: page.getByRole('button', { name: 'SA 118' }) })).toContainText('09:15')
  await hero.getByRole('button', { name: 'Arrivals' }).click()
  await expect(hero.getByRole('table', { name: 'NFL Arrivals' }).getByRole('columnheader', { name: 'From', exact: true })).toBeVisible()
  await expect(hero.getByRole('button', { name: 'NF 203' })).toBeVisible()
  await expect(hero.getByRole('button', { name: 'NF 204' })).toHaveCount(0)
  await page.getByLabel('French labels').check()
  await expect(hero.getByRole('button', { name: 'Arrivées' })).toHaveAttribute('aria-pressed', 'true')
  await expect(hero.getByRole('table', { name: 'NFL Arrivées' })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Junction departures' })).toBeVisible()
})

