import { expect, test } from '@playwright/test'

test('media queries follow the browser, replace subscriptions and clean up', async ({ page }) => {
  await page.setViewportSize({ width: 900, height: 800 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/e2e/fixtures/media-query.html')
  const first = page.getByTestId('first'), second = page.getByTestId('second'), motion = page.getByTestId('motion')
  await expect(first).toHaveText('false')
  await expect(second).toHaveText('false')
  await expect(motion).toHaveText('false')
  await expect(page.getByTestId('race')).toHaveText('true')
  await expect(page.locator('body')).toHaveAttribute('data-listeners', '3')
  const subscriptions = await page.locator('body').getAttribute('data-subscriptions')
  await page.getByRole('button', { name: 'Render 0', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Render 1', exact: true })).toBeVisible()
  await expect(page.locator('body')).toHaveAttribute('data-subscriptions', subscriptions!)
  await page.setViewportSize({ width: 600, height: 800 })
  await expect(first).toHaveText('true')
  await expect(second).toHaveText('true')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(motion).toHaveText('true')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(motion).toHaveText('false')
  await page.getByRole('button', { name: 'Replace query' }).click()
  await expect(first).toHaveText('false')
  await expect(second).toHaveText('false')
  await expect(page.locator('body')).toHaveAttribute('data-listeners', '3')
  await page.setViewportSize({ width: 900, height: 800 })
  await expect(first).toHaveText('true')
  await expect(second).toHaveText('true')
  await page.getByRole('button', { name: 'Toggle consumers' }).click()
  await expect(page.locator('body')).toHaveAttribute('data-listeners', '0')
  await page.setViewportSize({ width: 600, height: 800 })
  await page.getByRole('button', { name: 'Toggle consumers' }).click()
  await expect(first).toHaveText('false')
  await expect(page.locator('body')).toHaveAttribute('data-listeners', '3')
})
